export function getHighSchoolDistrict(ward: string, middleSchool: string): string | undefined {
  return highSchoolData[`${ward}:${middleSchool}`];
}

export function getAllTowns(): TownSuggestion[] {
  const towns: TownSuggestion[] = [];
  Object.keys(schoolData).forEach((ward) => {
    Object.keys(schoolData[ward]).forEach((town) => {
      towns.push({ ward, town });
    });
  });
  return towns;
}

export function getAllSchools(): SchoolSuggestion[] {
  const elementary = new Set<string>();
  const middle = new Set<string>();
  Object.keys(schoolData).forEach((ward) => {
    Object.keys(schoolData[ward]).forEach((town) => {
      Object.keys(schoolData[ward][town]).forEach((chome) => {
        const info = schoolData[ward][town][chome];
        elementary.add(info.elementary);
        middle.add(info.middle);
      });
    });
  });
  const schools: SchoolSuggestion[] = [];
  Array.from(elementary).sort().forEach(name => schools.push({ name, type: 'elementary' }));
  Array.from(middle).sort().forEach(name => schools.push({ name, type: 'middle' }));
  return schools;
}

export function getTownList(ward: string): string[] {
  return schoolData[ward] ? Object.keys(schoolData[ward]).sort() : [];
}

export function getChomeList(ward: string, town: string): string[] {
  return schoolData[ward] && schoolData[ward][town] ? Object.keys(schoolData[ward][town]) : [];
}

export function searchSchool(ward: string, town: string, chome: string): SearchResult | undefined {
  if (schoolData[ward] && schoolData[ward][town] && schoolData[ward][town][chome]) {
    const info = schoolData[ward][town][chome];
    return {
      elementary: info.elementary,
      middle: info.middle,
      note: info.note,
      highSchoolDistrict: getHighSchoolDistrict(ward, info.middle)
    };
  }
  return undefined;
}

export function searchTownAreas(ward: string, town: string): AreaData[] {
  if (!schoolData[ward] || !schoolData[ward][town]) return [];
  return Object.keys(schoolData[ward][town]).map(chome => {
    const info = schoolData[ward][town][chome];
    return {
      ward,
      town,
      chome,
      elementary: info.elementary,
      middle: info.middle,
      highSchoolDistrict: getHighSchoolDistrict(ward, info.middle)
    };
  });
}

export function searchSchoolAreas(schoolName: string): AreaData[] {
  const areas: AreaData[] = [];
  Object.keys(schoolData).forEach((ward) => {
    Object.keys(schoolData[ward]).forEach((town) => {
      Object.keys(schoolData[ward][town]).forEach((chome) => {
        const info = schoolData[ward][town][chome];
        if (info.elementary === schoolName || info.middle === schoolName) {
          areas.push({
            ward,
            town,
            chome,
            elementary: info.elementary,
            middle: info.middle,
            highSchoolDistrict: getHighSchoolDistrict(ward, info.middle)
          });
        }
      });
    });
  });
  return areas;
}
